"""Tests for skills/docs-impact/scripts/pages.py."""

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1] / "skills" / "docs-impact" / "scripts"
sys.path.insert(0, str(SCRIPTS))

from pages import detect_pages, missing_from_nav, page_url  # noqa: E402

REMOTE = "https://github.com/acme/widget.git"


def write(root: Path, rel: str, text: str = "") -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


class PagesTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)

    def test_mkdocs_detected_with_site_url(self):
        write(self.root, "mkdocs.yml", "site_name: W\nsite_url: https://docs.example.org/widget/\n")
        site = detect_pages(self.root, REMOTE)
        self.assertEqual(site.generator, "mkdocs")
        self.assertEqual(site.source_dir, "docs")
        self.assertEqual(site.base_url, "https://docs.example.org/widget/")
        self.assertIn("site/**", site.excludes)

    def test_mkdocs_directory_urls(self):
        write(self.root, "mkdocs.yml", "site_url: https://x.github.io/w/\n")
        site = detect_pages(self.root, None)
        self.assertEqual(page_url(site, "docs/a/b.md"), "https://x.github.io/w/a/b/")
        self.assertEqual(page_url(site, "docs/index.md"), "https://x.github.io/w/")
        self.assertEqual(page_url(site, "docs/a/index.md"), "https://x.github.io/w/a/")
        self.assertIsNone(page_url(site, "README.md"))
        write(self.root, "mkdocs.yml", "site_url: https://x.github.io/w\nuse_directory_urls: false\n")
        site = detect_pages(self.root, None)
        self.assertEqual(page_url(site, "docs/a/b.md"), "https://x.github.io/w/a/b.html")

    def test_jekyll_permalink_wins(self):
        write(self.root, "_config.yml", "url: https://j.example.org\nbaseurl: /kit\n")
        write(self.root, "guide/start.md", "---\ntitle: S\npermalink: /getting-started/\n---\nbody\n")
        write(self.root, "guide/other.md", "# other\n")
        write(self.root, "index.md", "# home\n")
        site = detect_pages(self.root, REMOTE)
        self.assertEqual(site.generator, "jekyll")
        self.assertEqual(site.base_url, "https://j.example.org/kit/")
        self.assertEqual(page_url(site, "guide/start.md"), "https://j.example.org/kit/getting-started/")
        self.assertEqual(page_url(site, "guide/other.md"), "https://j.example.org/kit/guide/other.html")
        self.assertEqual(page_url(site, "index.md"), "https://j.example.org/kit/")
        self.assertIn("_site/**", site.excludes)

    def test_docusaurus_base_url(self):
        write(self.root, "docusaurus.config.js",
              "module.exports = {\n  url: 'https://acme.github.io',\n  baseUrl: '/widget/',\n};\n")
        site = detect_pages(self.root, REMOTE)
        self.assertEqual(site.generator, "docusaurus")
        self.assertEqual(site.base_url, "https://acme.github.io/widget/")
        self.assertEqual(page_url(site, "docs/a/b.md"), "https://acme.github.io/widget/docs/a/b")
        self.assertIn(".docusaurus/**", site.excludes)
        self.assertIn("build/**", site.excludes)

    def test_cname_overrides_remote(self):
        write(self.root, "docs/CNAME", "docs.widget.dev\n")
        write(self.root, "docs/index.html", "<h1>x</h1>")
        write(self.root, ".github/workflows/p.yml", "- uses: actions/deploy-pages@v4\n")
        site = detect_pages(self.root, REMOTE)
        self.assertEqual(site.base_url, "https://docs.widget.dev/")

    def test_remote_fallback_url(self):
        write(self.root, "mkdocs.yml", "site_name: W\n")
        for remote, expected in [
            (REMOTE, "https://acme.github.io/widget/"),
            ("git@github.com:acme/widget.git", "https://acme.github.io/widget/"),
            ("https://github.com/acme/acme.github.io", "https://acme.github.io/"),
            ("https://gitlab.com/acme/widget.git", ""),
            (None, ""),
        ]:
            self.assertEqual(detect_pages(self.root, remote).base_url, expected, remote)
        site = detect_pages(self.root, None)
        self.assertIsNone(page_url(site, "docs/a.md"))

    def test_page_missing_from_mkdocs_nav(self):
        write(self.root, "mkdocs.yml",
              "site_name: W\nnav:\n  - Home: index.md\n  - Guide:\n    - 'Start': guide/start.md\n"
              "theme: material\n")
        site = detect_pages(self.root, REMOTE)
        self.assertEqual(site.nav_files, ("docs/index.md", "docs/guide/start.md"))
        got = missing_from_nav(site, ["docs/guide/start.md", "docs/new.md", "docs/img.png", "README.md"])
        self.assertEqual(got, ["docs/new.md"])

    def test_docusaurus_autogenerated_skips_nav(self):
        write(self.root, "docusaurus.config.ts", "export default { url: 'https://a.io', baseUrl: '/' };\n")
        write(self.root, "sidebars.ts", "{ type: 'autogenerated', dirName: '.' }\n")
        site = detect_pages(self.root, REMOTE)
        self.assertIsNone(site.nav_files)
        self.assertEqual(missing_from_nav(site, ["docs/new.md"]), [])
        write(self.root, "sidebars.ts", "module.exports = { s: ['intro', 'guide/start'] };\n")
        site = detect_pages(self.root, REMOTE)
        self.assertEqual(missing_from_nav(site, ["docs/intro.md", "docs/new.mdx"]), ["docs/new.mdx"])

    def test_actions_deploy_detected(self):
        write(self.root, "_config.yml", "title: x\n")
        write(self.root, ".github/workflows/docs.yml", "run: mkdocs gh-deploy --force\n")
        self.assertEqual(detect_pages(self.root, REMOTE).deploy, "actions")
        write(self.root, ".github/workflows/docs.yml", "run: echo hi\n")
        self.assertEqual(detect_pages(self.root, REMOTE).deploy, "unknown")

    def test_gh_pages_branch_detected(self):
        write(self.root, "_config.yml", "title: x\n")
        git = ["git", "-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false"]
        subprocess.run(["git", "init", "-b", "main"], cwd=self.root, check=True, capture_output=True)
        subprocess.run([*git, "commit", "--allow-empty", "-m", "x"], cwd=self.root, check=True,
                       capture_output=True)
        subprocess.run(["git", "branch", "gh-pages"], cwd=self.root, check=True, capture_output=True)
        self.assertEqual(detect_pages(self.root, REMOTE).deploy, "branch")

    def test_plain_repo_returns_none(self):
        write(self.root, "README.md", "# hi\n")
        write(self.root, "docs/a.md", "# a\n")
        self.assertIsNone(detect_pages(self.root, REMOTE))

    def test_malformed_config_falls_back(self):
        (self.root / "mkdocs.yml").write_bytes(b"\xff\xfe\x00nav:\n  - \x80\n")
        site = detect_pages(self.root, REMOTE)
        self.assertEqual(site.generator, "mkdocs")

    def test_non_literal_config_values_ignored(self):
        write(self.root, "docusaurus.config.js",
              "module.exports = {\n  url: process.env.SITE_URL,\n"
              "  baseUrl: process.env.BASE || '/',\n};\n")
        self.assertEqual(detect_pages(self.root, REMOTE).base_url, "https://acme.github.io/widget/")
        write(self.root, "_config.yml", "url: ${SITE}\nbaseurl: kit\n")
        (self.root / "docusaurus.config.js").unlink()
        self.assertEqual(detect_pages(self.root, REMOTE).base_url, "https://acme.github.io/widget/")

    def test_single_line_js_and_nested_yaml_keys(self):
        write(self.root, "docusaurus.config.js",
              "module.exports = { url: 'https://a.io', baseUrl: '/w/' };\n")
        self.assertEqual(detect_pages(self.root, None).base_url, "https://a.io/w/")
        (self.root / "docusaurus.config.js").unlink()
        write(self.root, "_config.yml", "author:\n  url: https://me.example\nurl: https://j.io\n")
        self.assertEqual(detect_pages(self.root, None).base_url, "https://j.io/")

    def test_docusaurus_only_docs_map_and_jekyll_readme(self):
        write(self.root, "docusaurus.config.js", "module.exports = { url: 'https://a.io', baseUrl: '/' };\n")
        site = detect_pages(self.root, None)
        self.assertIsNone(page_url(site, "README.md"))
        self.assertIsNone(page_url(site, "blog/x.md"))
        self.assertEqual(page_url(site, "docs/intro.md"), "https://a.io/docs/intro")
        (self.root / "docusaurus.config.js").unlink()
        write(self.root, "_config.yml", "url: https://j.io\n")
        site = detect_pages(self.root, None)
        self.assertEqual(page_url(site, "README.md"), "https://j.io/README.html")
        self.assertEqual(page_url(site, "index.md"), "https://j.io/")

    def test_jekyll_docs_source_outside_returns_none(self):
        write(self.root, "docs/_config.yml", "url: https://j.io\n")
        site = detect_pages(self.root, None)
        self.assertEqual(site.source_dir, "docs")
        self.assertIsNone(page_url(site, "README.md"))
        self.assertEqual(page_url(site, "docs/a.md"), "https://j.io/a.html")

    def test_mkdocs_docs_dir_normalised_and_markdown_nav(self):
        write(self.root, "mkdocs.yml", "docs_dir: ./manual\nnav:\n  - A: a.markdown\n")
        site = detect_pages(self.root, None)
        self.assertEqual(site.source_dir, "manual")
        self.assertEqual(missing_from_nav(site, ["manual/a.markdown", "manual/b.md"]), ["manual/b.md"])

    def test_cname_prefers_source_dir_then_root(self):
        write(self.root, "CNAME", "root.example\n")
        write(self.root, "docs/CNAME", "docs.example\n")
        write(self.root, "docs/index.html", "x")
        write(self.root, ".github/workflows/p.yml", "actions/deploy-pages\n")
        self.assertEqual(detect_pages(self.root, None).base_url, "https://docs.example/")

    def test_git_failure_gives_unknown_deploy(self):
        write(self.root, "_config.yml", "title: x\n")
        self.assertEqual(detect_pages(self.root, REMOTE).deploy, "unknown")


if __name__ == "__main__":
    unittest.main()
